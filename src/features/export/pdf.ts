/**
 * pdf.ts — Printable PDF cutting sheet (one page per board).
 */

import PDFDocument from 'pdfkit';
import { createWriteStream } from 'node:fs';
import { formatInches } from '../../core';
import type { BoardLayout, LayoutResult } from '../layout/types';

const PALETTE: [number, number, number][] = [
  [207, 232, 255],
  [255, 233, 199],
  [214, 245, 214],
  [243, 217, 243],
  [255, 242, 184],
  [217, 230, 255],
  [255, 217, 217],
  [224, 224, 255],
];

function rgbHex(r: number, g: number, b: number): string {
  const toHex = (v: number) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0');
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

export function exportLayoutPDF(path: string, result: LayoutResult): Promise<void> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 30 });
    const stream = createWriteStream(path);
    stream.on('finish', () => resolve());
    stream.on('error', reject);
    doc.pipe(stream);

    doc.fontSize(14).text(`Cutting plan — strategy: ${result.strategy}`, { align: 'center' });
    doc.fontSize(9).fillColor('#555');
    doc.text(
      `Total: ${result.totalUsedArea.toFixed(0)} in² used of ${result.totalBoardArea.toFixed(0)} in² (${result.totalYieldPct.toFixed(1)}%) | placed ${result.placedQuantity}/${result.totalRequiredQuantity} pieces | kerf ${formatInches(result.settings.kerf)} | trim ${formatInches(result.settings.trimAllowance)}`,
      { align: 'center' },
    );
    doc.moveDown(0.5);

    for (const layout of result.layouts) {
      if (doc.y > 60) doc.addPage();
      const b = layout.board;
      const boxW = doc.page.width - 60;
      const boxH = doc.page.height - doc.y - 50;
      const scale = Math.min(boxW / b.lengthIn, boxH / b.widthIn, 20);
      const ox = 30 + (boxW - b.lengthIn * scale) / 2;
      const oy = doc.y;

      doc.rect(ox, oy, b.lengthIn * scale, b.widthIn * scale).fill('#faf6ee').stroke('#000');
      doc.fontSize(9).fillColor('#000');
      doc.text(
        `${b.boardId} — ${b.species}, ${b.thicknessIn}" × ${b.widthIn}" × ${b.lengthIn}" — yield ${layout.yieldPct.toFixed(1)}% (score ${layout.score.toFixed(2)})`,
        ox,
        oy + b.widthIn * scale + 2,
      );

      let colorIdx = 0;
      for (const p of layout.placements) {
        const [r, g, bl] = PALETTE[colorIdx++ % PALETTE.length];
        doc
          .rect(ox + p.rect.x * scale, oy + p.rect.y * scale, p.rect.l * scale, p.rect.w * scale)
          .fill(rgbHex(r, g, bl))
          .stroke('#333');
        const label = `${p.partName || p.partId}\n${formatInches(p.rect.w)} × ${formatInches(p.rect.l)}${p.rotated ? ' (R)' : ''}`;
        doc.fontSize(7).fillColor('#000');
        const d = doc as unknown as {
          text(text: string, x: number, y: number, options: { width: number }): unknown;
        };
        d.text(label, ox + p.rect.x * scale + 1, oy + p.rect.y * scale + 1, { width: p.rect.l * scale - 2 });
      }
      for (const d of b.defects) {
        doc
          .rect(ox + d.x * scale, oy + d.y * scale, d.length * scale, d.width * scale)
          .fill('#ffdddd')
          .stroke('#a00');
        doc.fontSize(7).fillColor('#a00').text('DEFECT', ox + d.x * scale + 1, oy + d.y * scale + 1);
      }

      doc.y = oy + b.widthIn * scale + 18;
    }

    doc.addPage();
    doc.fontSize(12).fillColor('#000').text('Cut sequences');
    doc.moveDown(0.4);
    for (const layout of result.layouts) {
      doc.fontSize(9.5).text(`${layout.board.boardId}:`);
      for (const s of layout.cutSequence) doc.fontSize(8).fillColor('#333').text(`  ${s.label}`);
      doc.moveDown(0.2);
    }
    doc.moveDown(0.6);
    if (result.unplaced.length > 0) {
      doc.fontSize(11).fillColor('#b30000').text('Unplaced parts');
      doc.fontSize(8.5).fillColor('#333');
      for (const u of result.unplaced) doc.text(`  ${u.partName || u.partId} ×${u.quantity}: ${u.reason}`);
      doc.moveDown(0.6);
    }
    doc.fontSize(8).fillColor('#888').text('Generated by BoardFootCalc Desktop — Board Cutting Optimizer. Verify cuts against your saw setup before cutting.');

    doc.end();
  });
}
